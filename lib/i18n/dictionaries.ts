const dictionaries: Record<Locale, Dictionary> = { nl, en };

export function getDictionary(lang: Locale): Dictionary {
  return dictionaries[lang] ?? nl;
}

export function statusLabel(dict: Dictionary, status: string | null | undefined) {
  if (!status) return '';
  return dict.common.status[status] ?? status.replace(/_/g, ' ');
}
